    // Public members are reported by default here; IncludePublicApi = false would also run `dotnet msbuild` per project.
    private static readonly DeadCodeConfig Defaults = new() { IncludePublicApi = true };

    [Fact]
    public async Task ReportsUnreferencedMembersOfAnyAccessibility()
    {
        var reported = await AnalyzeAsync(Defaults, ("C.cs", """
            public class C
            {
                public static void Main() => new C(1).Used();
                public C(int value) { }
                public void Used() { }
                public void PublicUnused() { }
                internal int internalField;
                private string? PrivateProperty { get; set; }
                protected event System.EventHandler? ProtectedEvent;
                public static C operator +(C a, C b) => a;
            }
            """));

        Assert.Equal(["C.PublicUnused()", "C.internalField", "C.PrivateProperty", "C.ProtectedEvent", "C.operator +(C, C)"], reported);
    }

    [Fact]
    public async Task ReportsAnUnusedTypeOnceInsteadOfEachMember()
    {
        var reported = await AnalyzeAsync(Defaults, ("C.cs", """
            public class Unused
            {
                public void A() { }
                public int B { get; set; }
                public class Nested { public void C() { } }
            }
            """));

        Assert.Equal(["Unused"], reported);
    }

