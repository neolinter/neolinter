    [Fact]
    public async Task CommandWritesSarifAndReturnsFindings()
    {
        using var directory = new TestPaths.TempDirectory();
        WriteProject(directory, "App.csproj", ("C.cs", "public class Unused { }"));
        directory.Write(NeolinterConfig.FileName, """{ "deadCode": { "includePublicApi": true } }""");
        directory.Write("App.slnx", """<Solution><Project Path="App.csproj" /></Solution>""");

        await RestoreAsync(Path.Combine(directory.Path, "App.csproj"));

        var output = new StringWriter();
        var error = new StringWriter();
        var exitCode = await NeolinterCommand.RunAsync(["analyze", "dead-code", "-o", "out.sarif"], output, error, directory.Path);

        Assert.Equal(ExitCodes.Findings, exitCode);
        var sarif = await File.ReadAllTextAsync(Path.Combine(directory.Path, "out.sarif"));
        Assert.Contains("\"ruleId\": \"NLC0002\"", sarif);
        Assert.Contains("\"uri\": \"C.cs\"", sarif);
        Assert.Empty(output.ToString());
    }

