    private const string ProjectFile = """
        <Project Sdk="Microsoft.NET.Sdk">
          <PropertyGroup>
            <TargetFramework>net10.0</TargetFramework>
            <Nullable>enable</Nullable>
          </PropertyGroup>
        </Project>
        """;

    /// <summary>Analyses one project made of the given files. A file declaring <c>Main</c> or top-level statements makes it an executable.</summary>
    private static async Task<IReadOnlyList<string>> AnalyzeAsync(DeadCodeConfig config, params (string Path, string Content)[] files)
    {
        using var directory = new TestPaths.TempDirectory();
        var isExe = files.Any(f => f.Content.Contains("Main()", StringComparison.Ordinal) || f.Path == "Program.cs");
        WriteProject(directory, "App.csproj", files);
        if (isExe)
        {
            directory.Write("App.csproj", ProjectFile.Replace("<Nullable>", "<OutputType>Exe</OutputType><Nullable>", StringComparison.Ordinal));
        }

        return await AnalyzeProjectAsync(directory, "App.csproj", config);
    }

    private static async Task<IReadOnlyList<string>> AnalyzeProjectAsync(TestPaths.TempDirectory directory, string project, DeadCodeConfig config)
    {
        await RestoreAsync(Path.Combine(directory.Path, project));
        using var loaded = await SolutionLoader.LoadAsync(Path.Combine(directory.Path, project));
        return Names(await DeadCodeAnalyzer.AnalyzeAsync(loaded.Solution, config, directory.Path));
    }

    /// <summary>The analysis needs the framework references that only a restored project resolves.</summary>
    private static async Task RestoreAsync(string project)
    {
        var start = new System.Diagnostics.ProcessStartInfo("dotnet") { RedirectStandardOutput = true, RedirectStandardError = true };
        start.ArgumentList.Add("restore");
        start.ArgumentList.Add(project);
        using var process = System.Diagnostics.Process.Start(start)!;
        var output = await process.StandardOutput.ReadToEndAsync();
        await process.WaitForExitAsync();
        Assert.True(process.ExitCode == 0, output);
    }

    private static void WriteProject(TestPaths.TempDirectory directory, string project, params (string Path, string Content)[] files)
    {
        directory.Write(project, ProjectFile);
        foreach (var (path, content) in files)
        {
            directory.Write(path, content);
        }
    }

    private static List<string> Names(IReadOnlyList<Finding> findings) =>
        findings.Select(f => QuotedName().Match(f.Message).Groups[1].Value).ToList();

    [GeneratedRegex("'([^']*)'")]
    private static partial Regex QuotedName();
}
